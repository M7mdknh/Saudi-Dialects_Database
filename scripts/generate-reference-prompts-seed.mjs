import { readFile, writeFile } from "node:fs/promises";
import { validateGuidedPromptsDataset } from "./guided-prompts-validation.mjs";

/**
 * Deterministically regenerates the reference_prompts seed migration from
 * the authoritative data/guided-prompts.sa.ar.json. Rerunning this script
 * with an unchanged dataset produces byte-identical SQL (prompts are sorted
 * by stable id, all values are escaped consistently).
 *
 * The generated migration uses `insert ... on conflict (id) do nothing`, so
 * re-applying it against a database that already has these rows is a no-op:
 * it never duplicates a prompt and never overwrites an admin's later edits
 * (those go through the `upsert_reference_prompt` function, which bumps
 * `prompt_version` and is the only other writer of this table).
 *
 * Usage: npm run data:guided-prompts:seed
 * Output: supabase/migrations/0015_seed_reference_prompts.sql (committed to
 * git; applied like any other migration via `supabase db push`).
 */

const dataDir = new URL("../data/", import.meta.url);
const migrationsDir = new URL("../supabase/migrations/", import.meta.url);
const datasetUrl = new URL("guided-prompts.sa.ar.json", dataDir);
const catalogUrl = new URL("guided-prompts.sa.catalog.json", dataDir);
const outputUrl = new URL("0015_seed_reference_prompts.sql", migrationsDir);

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlBool(value) {
  return value ? "true" : "false";
}

async function main() {
  const dataset = JSON.parse(await readFile(datasetUrl, "utf8"));
  const catalog = JSON.parse(await readFile(catalogUrl, "utf8"));

  const errors = validateGuidedPromptsDataset(dataset, catalog);
  if (errors.length > 0) {
    throw new Error(
      `Refusing to generate a seed migration from an invalid dataset:\n${errors.map((e) => `  - ${e}`).join("\n")}`,
    );
  }

  const prompts = [...dataset.prompts].sort((a, b) => a.id.localeCompare(b.id));

  const rows = prompts.map((p) => {
    const categoryLabel = dataset.category_labels_ar[p.category];
    return `  (${sqlString(p.id)}, ${sqlString(p.category)}, ${sqlString(categoryLabel)}, ${sqlString(p.msa_lemma)}, ${sqlString(p.definition_ar)}, ${sqlString(p.scenario_ar)}, ${sqlString(p.part_of_speech)}, ${sqlString(p.answer_form)}, ${p.priority}, ${p.prompt_version}, ${sqlBool(p.is_active)}, ${dataset.schema_version})`;
  });

  const sql = `-- Generated by scripts/generate-reference-prompts-seed.mjs from
-- data/guided-prompts.sa.ar.json (the authoritative, version-controlled
-- dataset). Do not hand-edit; rerun \`npm run data:guided-prompts:seed\` and
-- commit the result instead. Idempotent: reapplying this migration never
-- duplicates a prompt and never overwrites a later admin edit, because
-- admin edits go through upsert_reference_prompt() and bump prompt_version,
-- while this seed only inserts rows that don't exist yet (ON CONFLICT DO
-- NOTHING).

insert into reference_prompts (
  id, category, category_label_ar, msa_lemma, definition_ar, scenario_ar,
  part_of_speech, answer_form, priority, prompt_version, is_active,
  dataset_schema_version
)
values
${rows.join(",\n")}
on conflict (id) do nothing;
`;

  await writeFile(outputUrl, sql, "utf8");
  console.log(
    `Wrote ${outputUrl.pathname} with ${prompts.length} prompt rows.`,
  );
}

await main();
